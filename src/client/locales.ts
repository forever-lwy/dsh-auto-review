export type Translate = (key: string, params?: Record<string, unknown>) => string

/** Fallback translator (tests, or before the locale service binds). */
export function fallbackT(key: string, params?: Record<string, unknown>): string {
  const template = zh[key] ?? key
  return params ? template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? '')) : template
}
